def _skit_rules() -> str:
    """寸劇チャンネル共通の禁止事項（style.skit のとき）。

    キャラが出来事を外から報告すると、何を書いても説明文になる（#134）。
    このルールは meme の引用スレ用にしか書いていなかったため、同じく skit を
    宣言している showa で「そういう段取りらしいのだ」という伝聞行が出た（#150）。
    """
    return """

**寸劇にする（説明にしないための最重要ルール）:**
キャラは**出来事を外から報告する解説者ではなく、その場にいる登場人物**です。
今まさに起きていることとして演じてください。

**禁止する言い回し（これがあると全部説明文になります）:**
  ✗「〜だそうよ」「〜と言われたわ」「〜と皆に返されたわ」「そこへ〜と」
  ✗ 誰かの発言・段取り・経緯を**要約して伝える**こと

**代わりに、その人に喋らせる:**
  ✗ ず「工場長が、納期を半分にしろと言われたそうなのだ」
  ○ 工場長「社長、納期を半分にしろとはどういうことですか！」
     ず「待つのだ、それ今から言うのだ!?」

**「〜と言われた」「〜という話だ」も報告です。** その場面を演じてください。

- 登場人物が増えるときは**声を変えます**（使える話者は speaker の候補にあるものだけ）。"""


def _ronron_rules() -> str:
    """ロンロン型の展開ルール（docs/02 2-2の実測を転記。#165→#166）。

    「キチガイっぽいのに知性を感じる」の正体は、前提を1個だけ壊して
    全員がその上で論理的に振る舞う分裂にある（8本の書き起こしで全て共通）。
    meme / trivia / heisei に共通で注入する。showa は別路線（#167）なので使わない。
    """
    return """

**展開の型（実測済み。ここから外れた台本は差し戻されます）:**
1. **前提を1個だけ壊す。** 壊すのは感情ではなく**言葉かロジック**です。実測での内訳:
   同音異義の押し通し（座右の銘→左右の目）／多義語の取り違えを指示どおり全力実行
   （つまみを出す→客をつまみ出す）／ルールの穴を突く制度ハック（自分で作って命名すれば
   何でも食える）／語彙の接合ミス（「すっかり真夏のこの頃」）。
   壊した前提の上で、**登場人物は全員論理的に振る舞う**。
   前提を2個以上壊すと、ただの出鱈目になって知性が消えます。
2. **ボケの当事者は最後まで大真面目。** 自覚・照れ・ネタバラシをした瞬間に壊れます。
   ツッコミ役だけが正気で、観客の代弁をします。
3. **シーン1は状況説明ではなくリアクションから始める。**
   何かが既に起きた後から開幕し、何が起きたかは伏せます（「厨房『なんやこの注文』」）。
4. **状況の説明は会話内の質問への回答として後出しする**（「何頼んだ？」方式）。
   ナレーション・報告で説明しない。
5. **オチは2択だけ**: (a) 感情への異常に精密な名づけ・例え（「野良猫を撫でた後
   ついて帰られる時みたいな申し訳なさ」）、(b) 冷静な一般化で被害者ぶる
   （「日本語も難しいよな」）。パワーワードはこのどちらかの行に置く。
6. **異常に具体的なディテールを1個入れる**（数字か固有の状況。「登録者16人」
   「保留BGMのサビ直前にガチャ」級）。与えられたネタの範囲内で選ぶこと。
7. **効果音は擬音の台詞として発声してよい**（「ルルルル」「ガチャ」「ポチ」「どすん」）。
   素人劇の作法が人間味になります。
8. **ネットスラングは台詞の中で使う**（ワイ・ンゴ・〜やで・草・ほな 等。
   キャラの口調に混ぜて自然に出す）。**caption・タイトルには入れない**
   （www 0%・【悲報】0%はタイトルの実測です。台詞は別）。"""


def _thread_rules(cfg: dict) -> str:
    """引用スレから作るときの追加ルール（v5: オチ逆算。docs/05 2章）。"""
    base = f"""

ネタ元のスレについて（v5・最重要）:
ネタ元として実在のスレ（転載自由のおーぷん2ちゃんねる）が与えられます。
**0からの創作はしません。面白さはスレが持っています。あなたの仕事は翻案とテンポです。**
- まずスレ全体を読み、オチ（いちばん面白い展開・結末・ツッコミ）を一文で特定する。
- 最後のシーンはそのオチで締める。オチのあとに解説やまとめを足さない（蛇足で台無しになる）。
- シーン1はスレタイの内容をフックにして、オチへの期待を作る。
- 本編（シーン2〜4）はスレの展開を時系列で刈り込み、レスの応酬を2人の掛け合いに翻案する。
  面白いレスの言い回しは活かしてよい（転載自由ソース）。ただしキャラの口調に直す。
- スレに無い展開・オチを創作しない。盛ってよいのは表現だけで、事実の水増しをしない。
- 実在の人物名・企業名・場所など特定につながる情報はぼかすか落とす。
- 誹謗中傷・差別・違法行為の推奨は拾わない。

**ただし、面白い部分まで削らないこと（重要）:**
このジャンルの面白さは**人間の本音・バカバカしさ・失敗・下品さ**にあります。
「上品にまとめる」と、事実だけが残って**説明文**になります。
- **残す**: 下品な発言・バカな決めつけ・自虐・見栄・恥ずかしい本音・的外れな助言・
  誰も聞いていない自分語り・急に始まる関係ない話
- **落とす**: 実在人物への誹謗中傷・個人の特定・差別・違法行為の推奨
- 「敬意を払う」のは**元ネタの文化**に対してであって、
  **スレの登場人物を上品に描き直すことではありません**。"""

    if cfg["name"] != "meme":
        return base + """
- シーン1の caption はスレタイを20字以内に整えたもの（スレタイとして全編表示される）。"""

    # このジャンルで51.2万に達したチャンネルは掲示板の記号を全部捨てている（docs/02 2章）。
    # 従来型（www・【悲報】・レス番号を出す型）は直近2,000〜3,000回まで衰退した
    return base + _skit_rules() + _ronron_rules() + f"""

**このチャンネルの配役:**
- **ずんだもんがスレ主**（相談する人・自慢する人・困っている人）を演じます。
- **他のキャラがレス民**を演じます。1人1レスではなく、性格を持った数人が絡みます。
- 「スレ主は〜」「レスでは〜」「このスレは〜」とは書きません。その人に喋らせます。

**掲示板の記号は「画面」から捨てる（セリフからは捨てない）:**
登録者51万のチャンネルはタイトルに `www` を0%、`【悲報】` を0%しか使っていません。
逆に、それらを使う従来型のチャンネルは再生数が2桁落ちています。
- **`w` `ｗ` `www` `【悲報】` `【朗報】` を caption に書かない。**
- **セリフの中はその逆で、ネットスラングを積極的に使う**（ワイ・ンゴ・〜やで・草・ほな 等）。
  実測でもセリフはスラングまみれで、綺麗な標準語に直した瞬間にAI量産感が出ます。
  ただしキャラの口調（語尾）は保ったまま混ぜること。
- **レス番号・アンカー（>>1）・ID・名前欄に触れない。** 「1が」「イッチが」は可。
- 「スレ」「掲示板」という語は最小限に。**普通の話として語る**。

**caption（スレタイ）の型:**
`【4〜6字の名詞句】` + 内容を言い切る短文。**全体で16字以内**（【】を含む）。
画面では8字で折り返されるため、17字を超えると3行になって画面を占有します。**必ず2行以内**。
- 良い例（16字以内）: 「【ルールの盲点】無限に買える自販機」「【妙な説得力】上司の遅刻理由」
- 名詞句は状態を言い切るもの（盲点／説得力／大誤算／総ツッコミ／方向音痴／完全論破 など）。
- 後半は体言止めで短く。助詞を削れるだけ削る。
- **悪い例: 「【悲報】〜ｗｗｗ」「2chで話題の〜」**

**オチは「パワーワード1個」に集約する:**
このジャンルは**視聴者がコメント欄で復唱したくなる短い言葉**が1個あるかで決まります。
- パワーワードは**既にこちらで決めてあります**（ユーザーメッセージで指定されます）。
  選び直さないでください。スレに実在する語であることを確認済みのものです。
- その語を `powerword` に入れ、**最後のシーンのセリフにそのままの形で1回置く**。
  画面ではその瞬間だけ**画面いっぱいの特大字幕**になります。
- パワーワードの後ろに説明を足さない。**言葉だけを残して終わる**のが正解。

**尺:**
この動画は**26〜32秒**に収めます（合計字数の上限は別途指定されます）。
その中で、**行の長さは揃えないでください**。
差し込みは5〜15字、スレ主が言い訳や自分語りをする場面は40字まで伸ばしてよい。
**全員が同じ長さの行を交互に出すと、一言コメント係の集まりになります。**
説明的な行を入れない。質問で終わる行は3行以下に抑える。"""


def _list_rules(cfg: dict, count: int) -> str:
    """「◯◯選」リスト形式のルール（heisei。docs/02 4章の実測）。

    掛け合い5シーンとは別の型。平成懐古で伸びているのは 2.5秒/ネタ の高速リストで、
    1本1ネタの情報提示型は185本出して1,000〜3,000回しか出ていない。
    """
    return f"""

**この動画は「◯◯選」のリスト形式です（掛け合い5シーンではありません）:**
裏取り済みのネタが複数与えられます。それを**次々に投げつける**構成にします。

- シーンは全部で{count + 2}個にします:
  - **シーン1 = 導入**。「◯◯年生まれ位が懐かしい△△{count}選」と宣言する（掛け合い2〜3行）。
    宣言の前に**ずんだもんのリアクションを1行置いて開幕する**
    （「は？　これ全部絶滅したのだ？」のように、驚いた後から始める）
  - **シーン2〜{count + 1} = 各ネタ**。1シーン1ネタ。**セリフは4行（2往復）**。
    名称と数字を出したあと、**その1件について会話を往復させる**。
    「名称→反応」で終わらせると一問一答になり、掛け合いになりません（#131）。

    ○ 良い例（2往復）:
      め「たまごっち。1年経たずに1000万個売れたのよ」
      ず「1000万人が世話してたのだ？　絶対に何割か死んでるのだ」
      め「死んだら墓が出るの。それも含めて流行ったのよ」
      ず「墓!?　おもちゃに墓を出す会社の気がしれないのだ」

    ✗ 悪い例（1往復で次へ）:
      め「たまごっち。1年経たずに1000万個」
      ず「え、1000万!?」
  - **シーン{count + 2} = 締め**（掛け合い2〜3行）
- **1シーンのセリフ合計は70字以内。これは絶対の上限です。**
  書き終えたら各シーンを数え、超えていたら短い方の行を削って収めてください
  （70字×{count}ネタで既に60秒に達します。超過は完走率に直結します）。
  ずんだもんの行は**20字以内**。感想（「多すぎなのだ」）ではなく、
  疑い・自分の話・**異常に精密な例え**（「それ暗号なのだ」）で返し、
  **めたんがそれに答える**ところまで書く。ネットスラング（草・〜やで等）は
  キャラの口調に混ぜて台詞内で使ってよい（captionには入れない）。
  平成の常識＝壊れた前提として扱い、**当時の人々は全員大真面目だった**ことを描く。
- 各ネタの caption は**その品名・名称そのもの**（10字以内）。
- **与えられたネタ以外を足さない。** 年代・名称は与えられたものだけを使う。

**タイトル（title）と シーン1の caption:**
- 「◯◯年生まれ**位**が懐かしい△△{count}選」の型にする。
- **「位（くらい）」を必ず入れる。** 断定すると対象年代の人しか自分ごとにできませんが、
  「位」があると前後10年が自分の話として見られます（実測でこの型が最も伸びている）。
- シーン1の caption は16字以内（画面は8字で折り返すので2行まで）。
  例: 「平成生まれが懐かしい{count}選」

**締めの作り方:**
- 「今どうなったか」か「当時は当たり前だった」の落差で終わる。
- 締めの最後の行は**感情への精密な名づけか、冷静な一般化**にする
  （「平成も難しいよな」型）。その行を powerword に入れる。
- **視聴者が年齢を名乗りたくなる終わり方にする**（「何年生まれ？」と直接聞くのではなく、
  「あなたはどれを覚えている？」のように思い出を語らせる）。
- リストは全部を網羅しません。**入りきらないものがあるのが正解**
  （視聴者が「◯◯が無い」と補完コメントを打つ余地を残す）。"""


def _fact_rules(cfg: dict) -> str:
    """裏取り済みの事実から作るときの追加ルール（trivia / heisei。docs/05 2章）。

    同じ「事実＋裏取り」でも、triviaは知らない話の種明かし、heiseiは
    知っている話の掘り起こしで、フックの作り方が正反対になる（#113）。
    """
    if (cfg.get("style") or {}).get("skit"):
        common = _skit_rules() + """

ネタ元の事実について（最重要）:
裏取り済みの事実が1つ与えられます。**事実の水増し・別の話の混入をしません。**
与えられた事実と一次ソースの範囲を超えて断定せず、数字・年代を盛りません。
事実が英語なら自然な日本語に直します。医療・投資・法律の助言に踏み込みません。"""
